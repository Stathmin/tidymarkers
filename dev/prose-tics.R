r_files <- list.files("R", pattern = "[.]R$", full.names = TRUE)
prose_files <- c(
  if (file.exists("DESCRIPTION")) "DESCRIPTION",
  if (file.exists("README.md")) "README.md",
  list.files("man", pattern = "[.]Rd$", full.names = TRUE),
  list.files("vignettes", pattern = "[.]Rmd$", full.names = TRUE)
)

# Whole file for docs; roxygen (`#'`) lines only for R sources.
prose_lines <- function(path) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  if (endsWith(path, ".R")) {
    keep <- grepl("^\\s*#'", lines)
    return(list(lines[keep], which(keep), rep(path, sum(keep))))
  }
  list(lines, seq_along(lines), rep(path, length(lines)))
}

# Every `#` line of an R source (roxygen included).
comment_lines <- function(path) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  keep <- grepl("^\\s*#", lines)
  list(lines[keep], which(keep), rep(path, sum(keep)))
}

# The broad tiers see docs, roxygen and ordinary comments in one pass.
all_source <- function() {
  out <- lapply(prose_files, prose_lines)
  for (f in r_files) out[[length(out) + 1L]] <- comment_lines(f)
  list(
    text = unlist(lapply(out, `[[`, 1L), use.names = FALSE),
    line = unlist(lapply(out, `[[`, 2L), use.names = FALSE),
    file = unlist(lapply(out, `[[`, 3L), use.names = FALSE)
  )
}

# The comment tier is coding comments only: R `#` lines, never docs.
r_comments_source <- function() {
  out <- lapply(r_files, comment_lines)
  list(
    text = unlist(lapply(out, `[[`, 1L), use.names = FALSE),
    line = unlist(lapply(out, `[[`, 2L), use.names = FALSE),
    file = unlist(lapply(out, `[[`, 3L), use.names = FALSE)
  )
}

scan <- function(patterns, tier, surface) {
  hits <- list()
  for (pat in patterns) {
    m <- grepl(pat, surface$text, ignore.case = TRUE, perl = TRUE)
    for (i in which(m)) {
      hits[[length(hits) + 1L]] <- data.frame(
        file = surface$file[[i]], line = surface$line[[i]], tier = tier,
        text = trimws(substr(surface$text[[i]], 1L, 160L)),
        stringsAsFactors = FALSE
      )
    }
  }
  if (!length(hits)) {
    return(NULL)
  }
  hits <- do.call(rbind, hits)
  # One row per line even when several patterns in the tier match it.
  hits[!duplicated(hits[c("file", "line")]), , drop = FALSE]
}

# A non-roxygen comment whose text equals the next code line adds nothing the
# code does not already say.
restating <- function(path) {
  x <- readLines(path, warn = FALSE, encoding = "UTF-8")
  hits <- list()
  for (i in seq_along(x)) {
    if (grepl("^\\s*#'", x[[i]])) next
    m <- regmatches(x[[i]], regexec("^\\s*#\\s?(.*)$", x[[i]]))[[1L]]
    if (!length(m)) next
    txt <- trimws(m[[2L]])
    if (!nzchar(txt)) next
    j <- i + 1L
    while (j <= length(x) && !nzchar(trimws(x[[j]]))) j <- j + 1L
    if (j > length(x) || startsWith(trimws(x[[j]]), "#")) next
    if (identical(gsub("\\s+", " ", txt), gsub("\\s+", " ", trimws(x[[j]])))) {
      hits[[length(hits) + 1L]] <- data.frame(
        file = path, line = i, tier = "comment",
        text = trimws(substr(x[[i]], 1L, 160L)), stringsAsFactors = FALSE
      )
    }
  }
  if (length(hits)) do.call(rbind, hits) else NULL
}

combine <- function(...) {
  hits <- Filter(Negate(is.null), list(...))
  if (length(hits)) do.call(rbind, hits) else NULL
}

verbose_hit <- function(file, line, text, tier) {
  data.frame(file = file, line = line, tier = tier, text = text,
             stringsAsFactors = FALSE)
}

# Long ordinary-comment blocks and over-wide comment lines.  Roxygen (`#'`) and
# the leading file banner are documentation, not commentary, so they are skipped.
comment_verbosity <- function() {
  hits <- list()
  for (f in r_files) {
    x <- readLines(f, warn = FALSE, encoding = "UTF-8")
    is_c <- grepl("^\\s*#", x) & !grepl("^\\s*#'", x)
    r <- rle(is_c)
    pos <- 0L
    for (k in seq_along(r$lengths)) {
      len <- r$lengths[[k]]
      banner <- pos == 0L && grepl("#\\s*===|#\\s*---", x[[1L]])
      if (r$values[[k]] && len >= 15L && !banner) {
        hits[[length(hits) + 1L]] <- verbose_hit(
          f, pos + 1L, sprintf("%d-line comment block", len), "comment_verbose"
        )
      }
      pos <- pos + len
    }
    long <- is_c & nchar(x) > 100L & !grepl("https?://", x)
    for (i in which(long)) {
      hits[[length(hits) + 1L]] <- verbose_hit(
        f, i, sprintf("%d-char comment line", nchar(x[[i]])), "comment_verbose"
      )
    }
  }
  if (length(hits)) do.call(rbind, hits) else NULL
}

# Prose paragraphs that ramble: long and uncited, or very long, plus long
# printed-output blocks.  Fenced code, tables and list items are not prose.
prose_verbosity <- function() {
  docs <- c(
    if (file.exists("README.md")) "README.md",
    list.files("vignettes", pattern = "[.]Rmd$", full.names = TRUE)
  )
  hits <- list()
  for (f in docs) {
    x <- readLines(f, warn = FALSE, encoding = "UTF-8")
    fence <- grepl("^\\s*```", x)
    in_code <- FALSE
    skip <- logical(length(x))
    for (i in seq_along(x)) {
      if (fence[[i]]) {
        in_code <- !in_code
        skip[[i]] <- TRUE
        next
      }
      skip[[i]] <- in_code
    }
    x[skip] <- ""
    blank <- !nzchar(trimws(x)) |
      grepl("^[[:space:]]*\\|", x) |
      grepl("^[[:space:]]*([-*+]|[0-9]+[.])\\s", x)
    r <- rle(!blank)
    pos <- 0L
    for (k in seq_along(r$lengths)) {
      len <- r$lengths[[k]]
      if (r$values[[k]]) {
        idx <- (pos + 1L):(pos + len)
        txt <- paste(x[idx], collapse = " ")
        words <- length(strsplit(trimws(txt), "\\s+")[[1L]])
        linked <- grepl(
          "\\]\\(|https?://|\\bdoi\\b|\\\\code\\{|`|[[:alnum:]_]+\\(\\)",
          txt, ignore.case = TRUE
        )
        if ((words > 120L && !linked) || words > 150L) {
          why <- if (words > 150L) {
            sprintf("%d-word paragraph", words)
          } else {
            sprintf("%d-word paragraph, no link", words)
          }
          hits[[length(hits) + 1L]] <- verbose_hit(
            f, pos + 1L, why, "prose_verbose"
          )
        }
      }
      pos <- pos + len
    }
    is_d <- grepl("^##", x)
    r <- rle(is_d)
    pos <- 0L
    for (k in seq_along(r$lengths)) {
      if (r$values[[k]] && r$lengths[[k]] >= 15L) {
        hits[[length(hits) + 1L]] <- verbose_hit(
          f, pos + 1L, sprintf("%d-line output block", r$lengths[[k]]),
          "prose_verbose"
        )
      }
      pos <- pos + r$lengths[[k]]
    }
  }
  if (length(hits)) do.call(rbind, hits) else NULL
}

report <- function(hits, name, gated) {
  tag <- if (gated) " (gated by --check)" else ""
  if (is.null(hits)) {
    message("  ", name, tag, ": 0")
    return(invisible())
  }
  message(
    "  ", name, tag, ": ", nrow(hits), " (", length(unique(hits$file)),
    " files)"
  )
  rows <- if (list_all) seq_len(nrow(hits)) else head(seq_len(nrow(hits)), 8L)
  for (i in rows) {
    message("    ", hits$file[i], ":", hits$line[i], "  ", hits$text[i])
  }
  extra <- nrow(hits) - length(rows)
  if (extra > 0L) message("    ... ", extra, " more (--list to show all)")
}

broad <- all_source()
r_comments <- r_comments_source()
results <- lapply(names(tics), function(tier) {
  surface <- if (identical(tier, "comment")) r_comments else broad
  scan(tics[[tier]]$patterns, tier, surface)
})
names(results) <- names(tics)
results$comment <- combine(
  results$comment,
  do.call(combine, lapply(r_files, restating))
)
if (!is.null(results$comment)) {
  results$comment <- results$comment[
    !duplicated(results$comment[c("file", "line")]), , drop = FALSE
  ]
}
results$comment_verbose <- comment_verbosity()
results$prose_verbose <- prose_verbosity()

if (only_contrastive) {
  report(results$negation, "negation", FALSE)
} else {
  message("prose tics")
  for (tier in names(tics)) {
    report(results[[tier]], tier, isTRUE(tics[[tier]]$gate))
  }
}

if (check) {
  gated <- names(tics)[vapply(tics, `[[`, logical(1), "gate")]
  found <- gated[!vapply(results[gated], is.null, logical(1))]
  if (length(found)) {
    stop(paste0(paste(found, collapse = "/"), " phrase(s) found"), call. = FALSE)
  }
}
