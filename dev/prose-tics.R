# =============================================================================
#  dev/prose-tics.R  --  report LLM wordiness in docs and code comments
# =============================================================================
#  A report, not a gate -- except for two tiers that must stay empty.
#
#  filler      phrases that carry no information and are a known LLM tell.
#              Gated by --check.
#  comment     coding-comment antipatterns: hedging ("obviously", "basically"),
#              meta-commentary about the author/tool, a TODO with no owner or
#              context, and a comment that merely restates the code below it.
#              Gated by --check (currently 0).
#  contrastive "X, not Y"; "rather than"; "not just". This repository's
#              deliberate teaching style -- hundreds of hits -- so it is printed
#              only with --contrastive and never gated.
#
#  Dev-only: `dev/` is in .Rbuildignore.
#
#  Scans: DESCRIPTION, README.md, man/*.Rd, vignettes/*.Rmd and the roxygen
#  (`#'`) lines of R/*.R for the prose tiers; every `#` line of R/*.R for the
#  comment tier. Code lines are not prose and are skipped there.
#
#  Run:  Rscript dev/prose-tics.R [--check] [--contrastive]
# =============================================================================

script <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
root <- if (length(script)) {
  dirname(dirname(normalizePath(sub("^--file=", "", script[[1L]]))))
} else {
  getwd()
}
setwd(root)

args <- commandArgs(trailingOnly = TRUE)
check <- "--check" %in% args
show_contrastive <- "--contrastive" %in% args

# `filler` and `comment` are gated by --check; `contrastive` is reported only.
tics <- list(
  filler = c(
    "it(')?s worth noting", "it is (important|worth) (to note|noting)",
    "\\bdelve", "\\btapestry", "\\bseamless", "\\bpivotal", "\\bcrucial",
    "\\bfurthermore", "\\bmoreover", "\\bthat said", "\\bleverag(e|ing)\\b"
  ),
  comment = c(
    "\\b(obviously|of course|basically|trivially|clearly)\\b",
    "\\b(as an ai|the agent|an llm|generated by|i (added|changed|fixed|updated|removed))\\b",
    "\\b(todo|fixme|xxx|hack)\\b"
  ),
  contrastive = c(
    "\\b(is|are|was|were)\\b[^.]{0,90},[[:space:]]+not\\b",
    "\\bnot\\b[^.]{0,60}\\bbut\\b", "\\brather than\\b",
    "\\bnot just\\b", "\\bnot only\\b", "\\badditionally\\b"
  )
)

r_files <- list.files("R", pattern = "[.]R$", full.names = TRUE)

# Prose: whole file for docs, roxygen (`#'`) lines only for R sources.
prose_lines <- function(path) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  if (endsWith(path, ".R")) {
    keep <- grepl("^\\s*#'", lines)
    return(list(lines[keep], which(keep)))
  }
  list(lines, seq_along(lines))
}

# Code comments: every `#` line of an R source (roxygen included).
comment_lines <- function(path) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  keep <- grepl("^\\s*#", lines)
  list(lines[keep], which(keep))
}

files <- c(
  if (file.exists("DESCRIPTION")) "DESCRIPTION",
  if (file.exists("README.md")) "README.md",
  list.files("man", pattern = "[.]Rd$", full.names = TRUE),
  list.files("vignettes", pattern = "[.]Rmd$", full.names = TRUE),
  r_files
)

scan <- function(patterns, tier, reader, sources) {
  hits <- list()
  for (f in sources) {
    p <- reader(f)
    text <- p[[1L]]
    lines <- p[[2L]]
    for (pat in patterns) {
      m <- grepl(pat, text, ignore.case = TRUE, perl = TRUE)
      for (i in which(m)) {
        hits[[length(hits) + 1L]] <- data.frame(
          file = f, line = lines[[i]], tier = tier,
          text = trimws(substr(text[[i]], 1L, 160L)),
          stringsAsFactors = FALSE
        )
      }
    }
  }
  if (length(hits)) do.call(rbind, hits) else NULL
}

# A non-roxygen comment whose text equals the next code line adds nothing the
# code does not already say.
restating <- function(path) {
  x <- readLines(path, warn = FALSE, encoding = "UTF-8")
  hits <- list()
  for (i in seq_along(x)) {
    if (grepl("^\\s*#'", x[[i]])) next
    m <- regmatches(x[[i]], regexec("^\\s*#\\s?(.*)$", x[[i]]))[[1L]]
    if (!length(m)) next
    txt <- trimws(m[[2L]])
    if (!nzchar(txt)) next
    j <- i + 1L
    while (j <= length(x) && !nzchar(trimws(x[[j]]))) j <- j + 1L
    if (j > length(x) || startsWith(trimws(x[[j]]), "#")) next
    if (identical(gsub("\\s+", " ", txt), gsub("\\s+", " ", trimws(x[[j]])))) {
      hits[[length(hits) + 1L]] <- data.frame(
        file = path, line = i, tier = "comment",
        text = trimws(substr(x[[i]], 1L, 160L)), stringsAsFactors = FALSE
      )
    }
  }
  if (length(hits)) do.call(rbind, hits) else NULL
}

combine <- function(...) {
  hits <- Filter(Negate(is.null), list(...))
  if (length(hits)) do.call(rbind, hits) else NULL
}

report <- function(hits, name) {
  if (is.null(hits)) {
    message("  ", name, ": 0")
    return(invisible())
  }
  message(
    "  ", name, ": ", nrow(hits), " (", length(unique(hits$file)), " files)"
  )
  for (i in seq_len(nrow(hits))) {
    message("    ", hits$file[i], ":", hits$line[i], "  ", hits$text[i])
  }
}

filler <- scan(tics$filler, "filler", prose_lines, files)
comment <- combine(
  scan(tics$comment, "comment", comment_lines, r_files),
  do.call(combine, lapply(r_files, restating))
)

message("prose tics")
report(filler, "filler (gated by --check)")
report(comment, "comment (gated by --check)")
if (show_contrastive) {
  report(
    scan(tics$contrastive, "contrastive", prose_lines, files),
    "contrastive (never gated)"
  )
} else {
  message("  contrastive: not scanned (pass --contrastive to list)")
}

if (check) {
  n <- (!is.null(filler)) + (!is.null(comment))
  if (n > 0L) {
    stop("filler/comment phrase(s) found", call. = FALSE)
  }
}
