# =============================================================================
#  dev/prose-tics.R  --  report LLM wordiness in docs and code comments
# =============================================================================
#  A report, not a gate -- except for the tiers that must stay empty.
#
#  filler      phrases that carry no information and are a known LLM tell.
#              Gated by --check.
#  comment     coding-comment antipatterns: hedging ("obviously", "basically"),
#              meta-commentary about the author/tool, a TODO with no owner or
#              context, and a comment that merely restates the code below it.
#              Gated by --check (currently 0).
#  negation    the "not X, it's Y" family in every shape: "is, not", "not but",
#              "not just", "rather than", "unlike", "far from". This is the
#              repository's deliberate teaching style, so it is reported, never
#              gated. --contrastive is an alias that lists only this tier.
#  meta        signposting and self-commentary: "the point is", "here's the
#              thing", "importantly", "note that", "at its heart", "serves as".
#  hedge       intensifiers and softeners: "simply", "really", "seems to",
#              "of course", "perhaps", "in fact".
#  verbosity   wordy phrases with a shorter equivalent: "in order to",
#              "the fact that", "prior to", "a number of".
#  punctuation em dashes and "!!", which prose rarely needs.
#  comment_verbose
#              a long ordinary-`#` block (>= 15 lines, banner excluded) or a
#              comment line wider than 100 columns.
#  prose_verbose
#              a prose paragraph over 120 words with no link, `code` or call,
#              a paragraph over 150 words, or a `##` output block over 15 lines.
#              Gated by --check (currently 0).
#
#  The report-only tiers are printed as counts plus a bounded sample; --list
#  prints every hit. filler, comment, verbosity and prose_verbose are gated;
#  the rest are report-only because their hits are mostly deliberate.
#
#  Dev-only: `dev/` is in .Rbuildignore.
#
#  Scans: DESCRIPTION, README.md, man/*.Rd, vignettes/*.Rmd and the roxygen
#  (`#'`) lines of R/*.R for the prose tiers; every `#` line of R/*.R for the
#  comment tier. Code lines are not prose and are skipped there.
#
#  Run:  Rscript dev/prose-tics.R [--check] [--list] [--contrastive]
# =============================================================================

script <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
root <- if (length(script)) {
  dirname(dirname(normalizePath(sub("^--file=", "", script[[1L]]))))
} else {
  getwd()
}
setwd(root)

args <- commandArgs(trailingOnly = TRUE)
check <- "--check" %in% args
list_all <- "--list" %in% args
only_contrastive <- "--contrastive" %in% args

